for (const img of IMAGES) {
  const path = `${DIR}/${img.file}`;
  let section = `\n${''.padEnd(70, '=')}\n### ${img.label}\nФайл: ${img.file}\n${''.padEnd(70, '-')}\n`;
  try {
    const b64 = fs.readFileSync(path).toString('base64');
    const res = await zai.chat.completions.createVision({
      model: 'glm-4.5v',
      thinking: { type: 'disabled' },
      messages: [
        { role: 'system', content: 'Ты — точный аналитик изображений. Отвечай по-русски, строго по изображению, дословно. Если что-то не читается или не уверен — скажи об этом прямо, не выдумывай.' },
        { role: 'user', content: [
          { type: 'image_url', image_url: { url: `data:image/png;base64,${b64}` } },
          { type: 'text', text: img.prompt },
        ]},
      ],
    });
    const raw = res?.choices?.[0]?.message?.content ?? JSON.stringify(res, null, 2);
    section += raw + '\n';
    console.log(`\n### ${img.label}\n${raw.slice(0, 1200)}\n`);
  } catch (e) {
    section += 'VLM_ERROR: ' + (e?.message ?? String(e)) + '\n';
    console.error(`VLM_ERROR ${img.file}:`, e?.message ?? e);
  }
  report += section;
}

fs.writeFileSync(OUT, report);
