def seg(start, end, new, tag):
    global txt
    assert txt.count(start) == 1, f'{tag} start: count!=1 СТОП'
    assert txt.count(end) == 1, f'{tag} end: count!=1 СТОП'
    a = txt.index(start)
    b = txt.index(end, a)
    assert new.endswith(end), f'{tag}: new не кончается end-якорем СТОП'
    txt = txt[:a] + new + txt[b + len(end):]
    print(f'SEG ok {tag}')

